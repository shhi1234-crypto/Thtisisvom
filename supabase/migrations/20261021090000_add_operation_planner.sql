-- Operations planner: administrator-only recurring and one-time deadlines.
-- Dates are resolved by the planner client so monthly tasks always roll forward
-- without creating duplicate rows every month.

create table public.operation_planner_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  description text,
  deadline_type text not null default 'ONE_TIME'
    check (deadline_type in ('ONE_TIME', 'MONTHLY_DAY', 'MONTHLY_RANGE')),
  deadline_date date,
  start_day smallint,
  end_day smallint,
  color_key text not null default 'VIOLET'
    check (color_key in ('VIOLET', 'MINT', 'AMBER', 'ROSE')),
  is_done boolean not null default false,
  completed_at timestamptz,
  completed_period date,
  sort_order integer not null default 0,
  constraint operation_planner_items_deadline_shape check (
    (deadline_type = 'ONE_TIME'
      and deadline_date is not null
      and start_day is null
      and end_day is null)
    or
    (deadline_type = 'MONTHLY_DAY'
      and deadline_date is null
      and start_day between 1 and 31
      and end_day is null)
    or
    (deadline_type = 'MONTHLY_RANGE'
      and deadline_date is null
      and start_day between 1 and 31
      and end_day between start_day and 31)
  )
);

alter table public.operation_planner_items enable row level security;

grant select, insert, update, delete on table public.operation_planner_items to authenticated;
grant usage, select on sequence public.operation_planner_items_id_seq to authenticated;

create policy "operation_planner_items_admin_only"
on public.operation_planner_items
for all
to authenticated
using (
  exists (
    select 1
    from public.admins
    where admins.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1
    from public.admins
    where admins.user_id = (select auth.uid())
  )
);


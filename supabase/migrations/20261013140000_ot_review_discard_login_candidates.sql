-- Keep application disposal auditable and prevent unlinked accounts from appearing in the login picker.
alter table public.ot_reviews
  add column if not exists discarded_at timestamptz,
  add column if not exists discarded_by uuid references auth.users(id),
  add column if not exists discard_reason text;

alter table public.ot_reviews
  drop constraint if exists ot_reviews_status_check;

alter table public.ot_reviews
  add constraint ot_reviews_status_check
  check (status = any (array['IN_REVIEW'::text,'APPROVED'::text,'REJECTED'::text,'DISCARDED'::text]));

create table if not exists public.ot_review_discard_log (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.ot_reviews(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id),
  actor_member_id bigint references public.members(id),
  actor_name text not null check (char_length(actor_name) between 1 and 80),
  reason text,
  created_at timestamptz not null default clock_timestamp()
);

create index if not exists ot_review_discard_log_review_created_idx
  on public.ot_review_discard_log(review_id, created_at desc);

alter table public.ot_review_discard_log enable row level security;
revoke all on table public.ot_review_discard_log from anon, authenticated;
grant all on table public.ot_review_discard_log to service_role;

create or replace view public.members_display as
select id, name, nickname, profile_image_url, role, is_active, join_order
from public.members
where is_active is true
  and auth_user_id is not null;

create or replace function public.vom_ot_discard_review(
  p_review_id bigint,
  p_actor_id uuid,
  p_actor_member_id bigint,
  p_actor_name text,
  p_reason text default null
) returns jsonb
language plpgsql
set search_path to ''
as $function$
declare
  review public.ot_reviews%rowtype;
  now_at timestamptz := clock_timestamp();
  clean_reason text := nullif(left(trim(coalesce(p_reason, '')), 500), '');
begin
  select * into review
  from public.ot_reviews
  where id = p_review_id
  for update;

  if not found then raise exception 'review_not_found'; end if;
  if review.completed_at is not null then raise exception 'review_completed'; end if;
  if review.status = 'DISCARDED' then raise exception 'review_already_discarded'; end if;
  if p_actor_id is null or char_length(trim(coalesce(p_actor_name, ''))) = 0 then
    raise exception 'discard_actor_required';
  end if;

  update public.ot_reviews
  set status = 'DISCARDED',
      resolved_at = coalesce(resolved_at, now_at),
      updated_at = now_at,
      discarded_at = now_at,
      discarded_by = p_actor_id,
      discard_reason = clean_reason
  where id = p_review_id;

  update public.ot_room_invites
  set revoked_at = coalesce(revoked_at, now_at)
  where review_id = p_review_id
    and revoked_at is null;

  insert into public.ot_review_discard_log(
    review_id, actor_user_id, actor_member_id, actor_name, reason, created_at
  ) values (
    p_review_id, p_actor_id, p_actor_member_id,
    left(trim(p_actor_name), 80), clean_reason, now_at
  );

  return jsonb_build_object(
    'review_id', p_review_id,
    'status', 'DISCARDED',
    'discarded_at', now_at
  );
end;
$function$;

revoke all on function public.vom_ot_discard_review(bigint, uuid, bigint, text, text)
  from public, anon, authenticated;
grant execute on function public.vom_ot_discard_review(bigint, uuid, bigint, text, text)
  to service_role;
